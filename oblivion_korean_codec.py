"""Encoder for the custom Korean byte scheme used by TheGreatestKorean fonts."""
NORMAL={0:0,2:1,3:2,5:3,6:4,7:5,9:6,11:7,12:8,14:9,15:10,16:11,17:12,18:13}
TENSE={1:14,4:15}; SPECIAL={8:0,10:1,13:2}
GROUP="bbbbbbbbcdddccdddccdb"
NO_SECOND=[0x80,0x8a,0x81,0x8c,0x82,0x8b,0x83,0x8d,0x84,0x90,0x8e,0x95,0x85,0x86,0x96,0x8f,0x97,0x87,0x88,0x98,0x89]
FINAL_SECOND=[0xa0,0xaa,0xa1,0xac,0xa2,0xab,0xa3,0xad,0xa4,0x99,0xae,0x9a,0xa5,0xa6,0x9b,0xaf,0x9c,0xa7,0xa8,0x9d,0xa9]
FINAL_SUFFIX=[0,1,0x13,0x15,2,0x16,0x17,3,4,0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,5,6,0x1f,7,0x14,8,0xc,0xe,0xf,0x10,0x11,0x12]

def encode_hangul(ch):
    n=ord(ch)-0xAC00
    if not 0<=n<11172: raise ValueError(ch)
    L=n//588; V=(n%588)//28; T=n%28; g=GROUP[V]
    if L in NORMAL or L in TENSE:
        idx=(NORMAL|TENSE)[L]
        first=({"b":0xb0,"c":0xc0,"d":0xd0} if not T else {"b":0xd0,"c":0xc0,"d":0xe0})[g]+idx
    else:
        idx=SPECIAL[L]
        first=({"b":0xf0,"c":0xf3,"d":0xf6} if not T else {"b":0xf6,"c":0xf3,"d":0xf9})[g]+idx
    out=bytes([first,(FINAL_SECOND if T else NO_SECOND)[V]])
    return out+(bytes([FINAL_SUFFIX[T]]) if T else b"")
